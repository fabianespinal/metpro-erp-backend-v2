-- ============================================================
-- Quoting v1 (Phase 1): template packs, item types, draft/final, totals fields
-- Target:   Supabase PostgreSQL (public schema)
-- Requires: PostgreSQL 13+
-- Status:   NOT APPLIED. Run only after explicit approval and DB verification.
-- Safe to re-run: every step is idempotent.
-- Additive only. No column type changes. No data rewrites.
-- Tax: tax_amount added, default 0. No tax rate or rule is enforced here.
-- ============================================================

BEGIN;

-- 1. Template packs (admin write, any authenticated user read)
CREATE TABLE IF NOT EXISTS template_packs (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text        NOT NULL,
    description text,
    created_at  timestamp   NOT NULL DEFAULT now(),
    updated_at  timestamp   NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS template_pack_categories (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pack_id     bigint  NOT NULL REFERENCES template_packs(id) ON DELETE CASCADE,
    name        text    NOT NULL,
    sort_order  integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS template_pack_items (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  bigint  NOT NULL REFERENCES template_pack_categories(id) ON DELETE CASCADE,
    product_id   bigint  NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    default_qty  numeric(12,2) NOT NULL DEFAULT 1,
    optional     boolean NOT NULL DEFAULT false,
    sort_order   integer NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS template_pack_categories_pack_idx
    ON template_pack_categories (pack_id);
CREATE INDEX IF NOT EXISTS template_pack_items_category_idx
    ON template_pack_items (category_id);

-- 2. quote_items: item type, description (services and custom items)
ALTER TABLE quote_items
    ADD COLUMN IF NOT EXISTS item_type   text NOT NULL DEFAULT 'product',
    ADD COLUMN IF NOT EXISTS description text;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'quote_items_item_type_check'
    ) THEN
        ALTER TABLE quote_items
            ADD CONSTRAINT quote_items_item_type_check
            CHECK (item_type IN ('product', 'service', 'custom'));
    END IF;
END
$$;

-- 3. quotes: totals fields, terms, finalize timestamp
ALTER TABLE quotes
    ADD COLUMN IF NOT EXISTS subtotal        numeric(12,2),
    ADD COLUMN IF NOT EXISTS discount_total  numeric(12,2),
    ADD COLUMN IF NOT EXISTS tax_amount      numeric(12,2) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS grand_total     numeric(12,2),
    ADD COLUMN IF NOT EXISTS terms           text,
    ADD COLUMN IF NOT EXISTS finalized_at    timestamp;

-- 4. public_token: nullable, no default. Existing rows keep their tokens.
--    New drafts stay NULL until finalize (application code sets the token).
ALTER TABLE quotes ALTER COLUMN public_token DROP DEFAULT;
ALTER TABLE quotes ALTER COLUMN public_token DROP NOT NULL;

COMMIT;
