-- Per-pack pricing overrides and per-pack dynamic charges.
-- Additive only. Current production code ignores the new column and table.
--
-- 1. template_pack_items.pack_price_override: nullable. NULL = use products.unit_price.
-- 2. template_pack_charges: up to 3 per pack (enforced in the API, PackIn.charges max_length=3).
--    type is percentage only for now. The CHECK is the single place to widen to 'fixed'
--    once quote dynamic charges support fixed amounts.
BEGIN;

ALTER TABLE public.template_pack_items
    ADD COLUMN IF NOT EXISTS pack_price_override numeric(12,2)
        CHECK (pack_price_override IS NULL OR pack_price_override >= 0);

CREATE TABLE IF NOT EXISTS public.template_pack_charges (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pack_id            bigint  NOT NULL REFERENCES public.template_packs(id) ON DELETE CASCADE,
    name               text    NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 60),
    type               text    NOT NULL DEFAULT 'percentage' CHECK (type IN ('percentage')),
    value              numeric(5,2) NOT NULL CHECK (value >= 0 AND value <= 100),
    enabled_by_default boolean NOT NULL DEFAULT true,
    sort_order         integer NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS template_pack_charges_pack_idx
    ON public.template_pack_charges (pack_id);

COMMIT;
