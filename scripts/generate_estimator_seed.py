"""Generate migrations/2026-10-22_estimator_seed_v1.sql from the workbook (source of truth).

Usage: python scripts/generate_estimator_seed.py WORKBOOK.xlsx > migrations/2026-10-22_estimator_seed_v1.sql
Profiles: workbook table F159:G301 (designation text, weight lb/ft). Constants and materials come from
the estimator package, which the parity tests prove equal to the workbook. Nothing is invented:
rows are loaded as found, defects included (D-8).
"""
import dataclasses
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import openpyxl  # noqa: E402

from estimator import RULE_REVISION, RULE_SET  # noqa: E402
from estimator.catalog import LINES  # noqa: E402
from estimator.constants import CONSTANT_NOTES, DEFAULT_CONSTANTS  # noqa: E402

PIE_ROWS = {88, 89, 99, 100, 107, 108, 109}
ITEM_TYPE = {115: "service", 116: "service", 120: "custom", 121: "custom"}


def q(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def profiles(path):
    ws = openpyxl.load_workbook(path, data_only=True).active
    out = []
    for r in range(159, 302):
        raw, weight = ws.cell(r, 6).value, ws.cell(r, 7).value
        if not raw or not isinstance(weight, (int, float)):
            continue
        m = re.fullmatch(r"\s*W\s*(\d+)\s*[xX×]\s*(\d+)\s*", str(raw))
        if not m:
            raise SystemExit(f"unparseable designation row {r}: {raw!r}")
        depth, last = int(m.group(1)), int(m.group(2))
        if last != weight:
            raise SystemExit(f"row {r}: designation weight {last} != column G {weight}")
        out.append((f"W{depth}x{last}", str(raw).strip(), depth, float(weight), r))
    names = [p[0] for p in out]
    if len(names) != len(set(names)):
        raise SystemExit("duplicate canonical designation")
    return out


def main(path):
    prof = profiles(path)
    if len(prof) != 132:
        raise SystemExit(f"expected 132 profiles, found {len(prof)}")
    o = []
    o.append("-- Engineering Estimate I1-b: seed for model 'Nave Industrial', version 1.0 (DRAFT).")
    o.append("-- Generated by scripts/generate_estimator_seed.py from the workbook. Do not edit by hand.")
    o.append("-- Version stays draft: activation is a separate, approved step. Skips if the model exists.")
    o.append("BEGIN;")
    o.append("DO $seed$")
    o.append("DECLARE m bigint; v bigint;")
    o.append("BEGIN")
    o.append("  IF EXISTS (SELECT 1 FROM public.estimator_models WHERE name = 'Nave Industrial') THEN RETURN; END IF;")
    o.append(f"  INSERT INTO public.estimator_models (name, rule_set) VALUES ('Nave Industrial', {q(RULE_SET)}) RETURNING id INTO m;")
    o.append(f"  INSERT INTO public.estimator_versions (model_id, version, rule_revision, status, notes) VALUES (m, '1.0', {RULE_REVISION}, 'draft', 'Seed from METPRO workbook, 2026-10-22. Defects carried (D-8).') RETURNING id INTO v;")
    for canon, raw, depth, w, row in prof:
        o.append(
            "  INSERT INTO public.estimator_profiles (version_id, designation, display_designation, family, depth_in, lb_per_ft, source_note) "
            f"VALUES (v, {q(canon)}, {q(raw)}, 'W', {depth}, {w}, {q(f'METPRO workbook table row {row}, 2026-10-22')});"
        )
    for f in dataclasses.fields(DEFAULT_CONSTANTS):
        cells, status, defects = CONSTANT_NOTES[f.name]
        value = getattr(DEFAULT_CONSTANTS, f.name)
        note = f"Typed in workbook formulas. Meaning not confirmed. {defects}".strip()
        o.append(
            "  INSERT INTO public.estimator_constants (version_id, key, kind, value, workbook_cell, status, note) "
            f"VALUES (v, {q(f.name)}, 'constant', {value}, {q(cells)}, 'unexplained', {q(note)});"
        )
    for i, ln in enumerate(LINES, start=1):
        basis = "ASSUMED linear foot" if ln.row in PIE_ROWS else None
        o.append(
            "  INSERT INTO public.estimator_materials (version_id, row_ref, sort_order, category, description, unit_label, unit_basis, "
            "driver_key, fixed_quantity, total_is_price, role_key, price, item_type) VALUES "
            f"(v, {ln.row}, {i}, {q(ln.category)}, {q(ln.label)}, {q(ln.unit)}, {q(basis)}, {q(ln.qty_cell)}, "
            f"{q(float(ln.fixed_qty) if ln.fixed_qty is not None else None)}, {q(ln.total_is_price)}, {q(ln.role)}, "
            f"{float(ln.price)}, {q(ITEM_TYPE.get(ln.row, 'product'))});"
        )
    o.append("END $seed$;")
    o.append("COMMIT;")
    print("\n".join(o))


if __name__ == "__main__":
    main(sys.argv[1])
