-- A1 Tax architecture: data-driven tax types, snapshotted on quotes and invoices.
-- Additive only. No existing row or column is changed.
--
-- 1. tax_types: code, label, rate (fraction, 0.1800 = 18%), active, is_default.
--    Seeded with two rows. Rates and labels live here, never in code.
--    The accounting treatment of construction_17_2017 is NOT decided here: the rate is applied the
--    same way as itbis_18 (tax_amount = rate * subtotal). Treatment is validated separately by the owner.
--    The type is decided automatically by the backend from the quote's indirect charges (approved 2026-10-22):
--    any of supervision, admin, insurance, transport, contingency selected -> construction_17_2017, else itbis_18.
--    Both types are seeded active. Deactivating construction_17_2017 makes quotes with those charges fail loudly.
-- 2. quotes and invoices get tax_type_code, tax_rate, tax_label (snapshot of the type at the time).
--    Every existing document was issued at 18% (verified 2026-10-22: 10 quotes, 4 invoices), so the
--    constant column default describes history. The default is dropped right after, so every new
--    row must set the three columns explicitly. Existing rows keep their values.
BEGIN;

CREATE TABLE IF NOT EXISTS public.tax_types (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        text         NOT NULL UNIQUE CHECK (code ~ '^[a-z0-9_]{2,40}$'),
    label       text         NOT NULL CHECK (length(btrim(label)) BETWEEN 1 AND 60),
    rate        numeric(7,4) NOT NULL CHECK (rate >= 0 AND rate <= 1),
    active      boolean      NOT NULL DEFAULT true,
    is_default  boolean      NOT NULL DEFAULT false,
    sort_order  integer      NOT NULL DEFAULT 0,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now()
);

-- At most one default type.
CREATE UNIQUE INDEX IF NOT EXISTS tax_types_one_default_idx
    ON public.tax_types (is_default) WHERE is_default;

INSERT INTO public.tax_types (code, label, rate, active, is_default, sort_order) VALUES
    ('itbis_18',              'ITBIS (18%)',        0.1800, true, true,  1),
    ('construction_17_2017',  'Construcción (Ley 17-2017)', 0.0180, true, false, 2)
ON CONFLICT (code) DO NOTHING;

-- Same posture as every other public table: RLS on, no policies. The backend connects as owner.
ALTER TABLE public.tax_types ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.quotes
    ADD COLUMN IF NOT EXISTS tax_type_code text         NOT NULL DEFAULT 'itbis_18'
        REFERENCES public.tax_types(code),
    ADD COLUMN IF NOT EXISTS tax_rate      numeric(7,4) NOT NULL DEFAULT 0.1800
        CHECK (tax_rate >= 0 AND tax_rate <= 1),
    ADD COLUMN IF NOT EXISTS tax_label     text         NOT NULL DEFAULT 'ITBIS (18%)';

ALTER TABLE public.invoices
    ADD COLUMN IF NOT EXISTS tax_type_code text         NOT NULL DEFAULT 'itbis_18'
        REFERENCES public.tax_types(code),
    ADD COLUMN IF NOT EXISTS tax_rate      numeric(7,4) NOT NULL DEFAULT 0.1800
        CHECK (tax_rate >= 0 AND tax_rate <= 1),
    ADD COLUMN IF NOT EXISTS tax_label     text         NOT NULL DEFAULT 'ITBIS (18%)';

-- History is described; new rows must say it themselves.
ALTER TABLE public.quotes   ALTER COLUMN tax_type_code DROP DEFAULT;
ALTER TABLE public.quotes   ALTER COLUMN tax_rate      DROP DEFAULT;
ALTER TABLE public.quotes   ALTER COLUMN tax_label     DROP DEFAULT;
ALTER TABLE public.invoices ALTER COLUMN tax_type_code DROP DEFAULT;
ALTER TABLE public.invoices ALTER COLUMN tax_rate      DROP DEFAULT;
ALTER TABLE public.invoices ALTER COLUMN tax_label     DROP DEFAULT;

COMMIT;
